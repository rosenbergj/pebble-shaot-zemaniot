#!/usr/bin/env python3
"""Convert the JSON fixtures into a static C header for the host test harness.

The JSON stays the reviewable ground truth (it is what gen_hebdate_fixture.py
and gen_zmanim_fixture.py produce from convertdate and PyEphem); this just
restates it as C literals so the harness needs no JSON parser.

    python3 test/gen/json_to_c.py

Writes test/c/fixtures.h.
"""

import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[2]
FIXTURES = ROOT / "test" / "fixtures"
OUT = ROOT / "test" / "c" / "fixtures.h"


def main():
    hebdate = json.loads((FIXTURES / "hebdate.json").read_text())
    zmanim = json.loads((FIXTURES / "zmanim.json").read_text())

    lines = [
        "// GENERATED by test/gen/json_to_c.py -- do not edit.",
        "// Source: test/fixtures/hebdate.json, test/fixtures/zmanim.json",
        "",
        "#ifndef FIXTURES_H",
        "#define FIXTURES_H",
        "",
        "typedef struct {",
        "  int g[3];",
        "  int h[3];",
        "  int leap;",
        "} HebDateFixture;",
        "",
        "typedef struct {",
        "  int year;",
        "  int n;",
        "  int lengths[13];",
        "} HebMonthLenFixture;",
        "",
        "typedef struct {",
        "  const char *name;",
        "  double lat, lon;",
        "  double t, prev, next;",
        "  int prev_rising;",
        "  int has_tzeit;",
        "  double tzeit_next;",
        "} ZmanimFixture;",
        "",
    ]

    dates = hebdate["dates"]
    lines.append("static const HebDateFixture HEB_DATES[] = {")
    for d in dates:
        g, h = d["g"], d["h"]
        lines.append(
            "    {{%d, %d, %d}, {%d, %d, %d}, %d},"
            % (g[0], g[1], g[2], h[0], h[1], h[2], 1 if d["leap"] else 0)
        )
    lines.append("};")
    lines.append("#define HEB_DATES_N %d" % len(dates))
    lines.append("")

    mls = hebdate["monthLengths"]
    lines.append("static const HebMonthLenFixture HEB_MONTH_LENS[] = {")
    for m in mls:
        lengths = m["lengths"]
        padded = lengths + [0] * (13 - len(lengths))
        lines.append(
            "    {%d, %d, {%s}},"
            % (m["year"], len(lengths), ", ".join(str(x) for x in padded))
        )
    lines.append("};")
    lines.append("#define HEB_MONTH_LENS_N %d" % len(mls))
    lines.append("")

    lines.append("static const ZmanimFixture ZMANIM[] = {")
    for z in zmanim:
        tz = z.get("tzeitNext")
        lines.append(
            '    {"%s", %.6f, %.6f, %.1f, %.1f, %.1f, %d, %d, %.1f},'
            % (
                z["name"],
                z["lat"],
                z["lon"],
                float(z["t"]),
                float(z["prev"]),
                float(z["next"]),
                1 if z["prevRising"] else 0,
                0 if tz is None else 1,
                0.0 if tz is None else float(tz),
            )
        )
    lines.append("};")
    lines.append("#define ZMANIM_N %d" % len(zmanim))
    lines.append("")
    lines.append("#endif")
    lines.append("")

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines))
    print(
        "wrote %s: %d dates, %d month-length years, %d zmanim cases"
        % (OUT.relative_to(ROOT), len(dates), len(mls), len(zmanim))
    )


if __name__ == "__main__":
    main()
